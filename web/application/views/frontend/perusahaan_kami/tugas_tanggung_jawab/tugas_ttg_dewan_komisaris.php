                          <li>kode etik yang berlaku bagi seluruh anggota Dewan Komisaris dan anggota Direksi, karyawan/ pegawai, serta pendukung organ yang dimiliki Perseroan, sesuai dengan ketentuan peraturan perundangan yang berlaku.</li><br>
